    public void validacioncaracteres(java.awt.event.KeyEvent event){
    
        if (event.getKeyChar()>=32 && event.getKeyChar() <=47 || event.getKeyChar()>=123 && event.getKeyChar() <=208 || event.getKeyChar()>=210 && event.getKeyChar() <=240
                || event.getKeyChar()>=242 && event.getKeyChar() <=255){
            
            event.consume();
            JOptionPane.showMessageDialog(null, "No se permiten carácteres espciales");
             
        }
        
        
    }

    public void validacion(){
       String id_provedor = jTextField1.getText().toString().toUpperCase();
       String nombre_provedor = jTextField2.getText().toLowerCase();
       String Empresa_provedor = jTextField3.getText().toLowerCase();
       String Fecha_provedor = jTextField4.getText().toLowerCase();
        try{
          if(jTextField1.getText().isEmpty() || id_provedor.length()!=5){
              
               JOptionPane.showMessageDialog(null,"No puedes dejar el campo vacio o ingresar un id diferente de 5 caracteres");
          }else{
              provedor.setId_provedor(id_provedor);
              if(jTextField2.getText().isEmpty()){
            
              JOptionPane.showMessageDialog(null,"No puedes dejar el campo nombre vacio");
              }else{
                  provedor.setNombre_del_provedor(nombre_provedor);
                  if(jTextField3.getText().isEmpty()){
                    
                     JOptionPane.showMessageDialog(null,"No puedes dejar el campo empresa vacio");
                  }else{
                   provedor.setEmpresa(Empresa_provedor);
                   if(jTextField4.getText().isEmpty()){
                    
                     JOptionPane.showMessageDialog(null,"No puedes dejar el campo fecha vacio");
                  }else{
                      provedor.setFecha_de_Entrega(Fecha_provedor);
                       metodos.guardar(provedor);
                       metodos.guardarArchivo(provedor);
                       JOptionPane.showMessageDialog(null,"Registro existoso");
                             jTextField1.setText("");
                             jTextField2.setText("");
                             jTextField3.setText("");
                             jTextField4.setText("");
                   }}
              }
          }

        
        }catch(Exception e){
        JOptionPane.showMessageDialog(this, e);
        
        }

    }
    
    
